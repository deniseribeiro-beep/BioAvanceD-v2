"""Extract a binary docs release (.xlsx workbooks, .docx documents) into
grep-friendly Markdown.

Usage:
    python scripts/docs-extract/extract_docs.py <src-dir> <out-dir>

Every .xlsx in <src-dir> (top level only) becomes one Markdown file per
sheet, named <prefix>-<SHEET>.md, where <prefix> comes from PREFIXES below
or else the workbook's stem. Every .docx becomes one Markdown file via
pandoc (GitHub-flavoured Markdown). An INDEX.md lists what was written,
with each source file's sha256 so a later run can tell whether the release
changed.

Requires: openpyxl, and pandoc on PATH for .docx.
"""
import datetime
import hashlib
import pathlib
import re
import subprocess
import sys

import openpyxl

# Short, stable names for the release's known files. Anything not listed
# falls back to its own stem, so a new file is still extracted.
PREFIXES = {
    "BioAvanceD_Dicionario_Dados_Consolidado": "dict",
    "BioAvanceD_Matriz_Rastreabilidade_Modelo": "matriz",
    "BioAvanceD_Requisitos_Funcionais_Nao_Funcionais": "requisitos",
    "BioAvanceD_Plano_Integrado_Foundation_Data_Pipeline": "plano",
    "BioAvanceD_Relatorio_Consistencia_Modelo": "relatorio-consistencia",
    "BioAvanceD_Modelo_Persistencia_Poliglota": "persistencia-poliglota",
    "BioAvanceD_Protocolo_Avaliacao_Ex_Ante_Identificacao_Fisica": "protocolo-ex-ante",
}


def prefix_for(stem):
    base = re.sub(r"_v\d+(\.\d+)*$", "", stem)
    return PREFIXES.get(base, stem)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cell(v):
    if v is None:
        return ""
    if isinstance(v, datetime.datetime):
        s = v.date().isoformat() if v.time() == datetime.time(0) else v.isoformat()
    elif isinstance(v, datetime.date):
        s = v.isoformat()
    elif isinstance(v, float) and v.is_integer():
        s = str(int(v))
    else:
        s = str(v)
    return s.replace("\\", "\\\\").replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def sheet_to_md(ws, title):
    rows = [list(r) for r in ws.iter_rows(values_only=True)]
    rows = [r for r in rows if any(c not in (None, "") for c in r)]
    if not rows:
        return f"# {title}\n\n(empty sheet)\n"
    width = max(max((i + 1 for i, c in enumerate(r) if c not in (None, "")), default=0) for r in rows)
    # The header is the first row that fills at least half the width; rows
    # above it are the sheet's preamble (titles, notes) and stay as text.
    hdr_i = next((i for i, r in enumerate(rows) if sum(c not in (None, "") for c in r[:width]) * 2 >= width), 0)
    out = [f"# {title}", ""]
    for r in rows[:hdr_i]:
        out.append(" ".join(cell(c) for c in r if c not in (None, "")))
        out.append("")
    table = [[cell(c) for c in (r + [None] * width)[:width]] for r in rows[hdr_i:]]
    out.append("| " + " | ".join(table[0]) + " |")
    out.append("|" + "---|" * width)
    for r in table[1:]:
        out.append("| " + " | ".join(r) + " |")
    return "\n".join(out) + "\n"


def main(src, dst):
    src, dst = pathlib.Path(src), pathlib.Path(dst)
    dst.mkdir(parents=True, exist_ok=True)
    index = []
    for f in sorted(src.iterdir()):
        if f.suffix.lower() == ".xlsx":
            pre = prefix_for(f.stem)
            wb = openpyxl.load_workbook(f, read_only=True, data_only=True)
            outs = []
            for ws in wb.worksheets:
                name = f"{pre}-{ws.title}.md"
                (dst / name).write_text(sheet_to_md(ws, f"{f.name} :: {ws.title}"), encoding="utf-8")
                outs.append(name)
            index.append((f.name, sha256(f), outs))
        elif f.suffix.lower() == ".docx":
            name = f"{prefix_for(f.stem)}.md"
            subprocess.run(
                ["pandoc", str(f), "-t", "gfm", "--wrap=none", "-o", str(dst / name)],
                check=True,
            )
            index.append((f.name, sha256(f), [name]))
    lines = [
        "# Extracted docs index",
        "",
        f"Generated by `scripts/docs-extract/extract_docs.py` from `{src.as_posix()}`.",
        "Do not edit these files by hand: re-run the script against the release.",
        "",
        "| Source | sha256 | Extracted |",
        "|---|---|---|",
    ]
    for name, digest, outs in index:
        lines.append(f"| {name} | `{digest}` | " + ", ".join(f"[{o}]({o})" for o in outs) + " |")
    (dst / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(index)} source files -> {sum(len(o) for _, _, o in index)} Markdown files in {dst}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
